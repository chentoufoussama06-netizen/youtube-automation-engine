#!/usr/bin/env node
/**
 * Render an AFTERCACHE case-file short from real evidence STILLS as animated
 * "pinned photo" cards: each real image (nothing cropped/cut — always
 * contain, never crop, per house rule) gets a cream paper border, a soft
 * drop shadow and a slight tilt, sits on the brand's near-black background,
 * and slowly zooms (Ken Burns via zoompan). A typed-out CASE/STATUS stamp
 * (brand amber/cyan, monospace) plays once near the start and holds, plus a
 * light vignette and a small synthesized SFX bed (sub-thump on hard cuts,
 * keystroke ticks under the stamp typing) — no downloaded assets, everything
 * generated by ffmpeg itself.
 *
 * Renders each still as its OWN small sequential ffmpeg process rather than
 * one filter_complex with all 7 image inputs and heavy per-branch filtering
 * running in parallel — that combined form reproducibly deadlocked (0% CPU,
 * no progress) on this machine once free memory dropped under a few GB.
 * Sequential processes fully release memory on exit between stills, keeping
 * peak memory far lower; each step here is individually small and fast.
 *
 * Caption typography lives in the .ass file itself (monospace, brand warm
 * white) rather than here — see data/aftercache/shorts/captions/*.ass.
 *
 * This is a from-scratch pipeline, NOT shorts-factory's renderShort() — that
 * one crops stock b-roll to fill the panel, which is wrong here because the
 * still IS the evidence; cropping it hides part of what's real.
 *
 *   DATA_ROOT=data/aftercache node scripts/render-case-evidence.js ac-revival
 *
 * Expects (all under DATA_ROOT):
 *   reference/case-<job.caseNumber>/*.jpg   real evidence stills, used in
 *                                            filename order
 *   shorts/audio/<jobId>_short.mp3          narration (already rendered)
 *   shorts/captions/<jobId>_short.ass       captions (already rendered)
 * Writes:
 *   shorts/video/<jobId>_short.mp4
 */
require('dotenv').config();

const fsp = require('fs').promises;
const path = require('path');
const os = require('os');
const { execFile } = require('child_process');
const { promisify } = require('util');
const execFileAsync = promisify(execFile);
const ffmpegPath = require('ffmpeg-static');
const { ShortsFactory } = require('../../utils/shorts-factory');

const ROOT = path.join(__dirname, '..', '..');
const DATA_ROOT = process.env.DATA_ROOT || 'data';
const QUEUE_PATH = process.env.QUEUE_PATH || path.join(ROOT, DATA_ROOT, 'queue.json');
const SHORTS_DIR = path.join(ROOT, DATA_ROOT, 'shorts');
const REFERENCE_DIR = path.join(ROOT, DATA_ROOT, 'reference');

// Brand doc palette (see project_aftercache-channel memory): near-black bg,
// warm white paper, cyan/amber accents. ASS colours are &H00BBGGRR.
const BG = '0x08090B';
const PAPER = '0xE8E8E3';
const AMBER_ASS = '&H004DB8FF';
const CYAN_ASS = '&H00FFE45D';

const ROTATIONS = [-3, 3, -2.5, 2, -3.5, 2.5, -2, 3.2, -2.8, 2.2];

function assTime(t) {
  const h = Math.floor(t / 3600);
  const m = Math.floor((t % 3600) / 60);
  const s = t % 60;
  return `${h}:${String(m).padStart(2, '0')}:${s.toFixed(2).padStart(5, '0')}`;
}

function typewriterEvents(text, startTime, charDur, styleName, holdUntil) {
  const lines = [];
  const times = [];
  let t = startTime;
  for (let i = 1; i <= text.length; i++) {
    const substr = text.slice(0, i).replace(/\\/g, '\\\\').replace(/[{}]/g, '');
    const segEnd = i === text.length ? holdUntil : t + charDur;
    lines.push(`Dialogue: 0,${assTime(t)},${assTime(segEnd)},${styleName},,0,0,0,,${substr}`);
    times.push(t);
    t += charDur;
  }
  return { lines, times };
}

async function buildStampAss(job, duration, outPath) {
  const caseText = `CASE ${job.caseNumber}`;
  const statusText = `STATUS: ${(job.caseStatus || 'ACTIVE').toUpperCase()}`;
  const charDur = 0.045;
  const caseStart = 0.3;
  const caseEv = typewriterEvents(caseText, caseStart, charDur, 'CaseStamp', duration);
  const statusStart = caseStart + caseText.length * charDur + 0.15;
  const statusEv = typewriterEvents(statusText, statusStart, charDur, 'StatusStamp', duration);

  const content = `[Script Info]
ScriptType: v4.00+
PlayResX: 1080
PlayResY: 1920
WrapStyle: 2

[V4+ Styles]
Format: Name,Fontname,Fontsize,PrimaryColour,SecondaryColour,OutlineColour,BackColour,Bold,Italic,Underline,StrikeOut,ScaleX,ScaleY,Spacing,Angle,BorderStyle,Outline,Shadow,Alignment,MarginL,MarginR,MarginV,Encoding
Style: CaseStamp,Consolas,58,${AMBER_ASS},&H000000FF,&H00000000,&H00000000,-1,0,0,0,100,100,2,0,1,5,2,7,50,50,60,1
Style: StatusStamp,Consolas,42,${CYAN_ASS},&H000000FF,&H00000000,&H00000000,-1,0,0,0,100,100,2,0,1,4,2,7,50,50,135,1

[Events]
Format: Layer,Start,End,Style,Name,MarginL,MarginR,MarginV,Effect,Text
${[...caseEv.lines, ...statusEv.lines].join('\n')}
`;
  await fsp.writeFile(outPath, content);
  return [...caseEv.times, ...statusEv.times];
}

async function buildSfxBed(events, totalDuration, outPath) {
  const args = ['-f', 'lavfi', '-i', `anullsrc=r=44100:cl=mono:d=${totalDuration.toFixed(2)}`];
  const filters = [];
  const mixLabels = ['[0:a]'];
  let nextInput = 1;
  events.forEach((ev, idx) => {
    const delayMs = Math.max(0, Math.round(ev.time * 1000));
    if (ev.type === 'thump') {
      args.push('-f', 'lavfi', '-i', 'sine=frequency=70:duration=0.18:sample_rate=44100');
      filters.push(`[${nextInput}:a]afade=t=out:st=0.02:d=0.16,volume=0.9,adelay=${delayMs}[sfx${idx}]`);
    } else {
      args.push('-f', 'lavfi', '-i', 'sine=frequency=1800:duration=0.02:sample_rate=44100');
      filters.push(`[${nextInput}:a]afade=t=out:st=0:d=0.02,volume=0.45,adelay=${delayMs}[sfx${idx}]`);
    }
    mixLabels.push(`[sfx${idx}]`);
    nextInput++;
  });
  filters.push(`${mixLabels.join('')}amix=inputs=${mixLabels.length}:duration=first:dropout_transition=0[out]`);

  const scriptPath = `${outPath}.filters.txt`;
  await fsp.writeFile(scriptPath, filters.join(';'));
  args.push('-filter_complex_script', scriptPath, '-map', '[out]', '-c:a', 'pcm_s16le', '-y', outPath);
  try {
    await execFileAsync(ffmpegPath, args, { maxBuffer: 1024 * 1024 * 50 });
  } finally {
    await fsp.unlink(scriptPath).catch(() => {});
  }
}

// One still -> one small silent card clip. Single input, single process:
// this is the unit that stays fast even under memory pressure.
async function renderCardClip(stillPath, index, segment, framesPerClip, outPath) {
  const angle = ROTATIONS[index % ROTATIONS.length];
  // Ken Burns via scale-up + time-varying crop, NOT zoompan. zoompan on this
  // exact upstream chain (rgba compositing -> zoompan) reproducibly deadlocked
  // at 0% CPU on this machine regardless of formula, memory state, or a full
  // reboot — isolated by bisecting the filter chain piece by piece. Plain
  // scale+crop with per-frame time expressions is a standard, more predictable
  // way to get the same panning-zoom feel.
  const panRight = index % 2 === 0;
  const xExpr = panRight ? `(iw-1080)*t/${segment.toFixed(2)}` : `(iw-1080)*(1-t/${segment.toFixed(2)})`;
  const yExpr = `(ih-1920)*t/${segment.toFixed(2)}`;
  const filters = [
    `[0:v]scale='min(920,iw)':'min(1500,ih)':force_original_aspect_ratio=decrease,setsar=1[photo]`,
    `[photo]pad=iw+44:ih+44:22:22:color=${PAPER}[bordered]`,
    `[bordered]format=rgba,rotate=${angle}*PI/180:fillcolor=none:ow=rotw(${angle}*PI/180):oh=roth(${angle}*PI/180)[rot]`,
    `[rot]split=2[card][shsrc]`,
    `[shsrc]colorchannelmixer=rr=0:gg=0:bb=0:aa=0.5,gblur=sigma=10[shadow]`,
    `color=c=${BG}:s=1080x1920:d=${segment.toFixed(2)}:r=30,format=rgba[bg]`,
    `[bg][shadow]overlay=(W-w)/2+14:(H-h)/2+18[bgsh]`,
    `[bgsh][card]overlay=(W-w)/2:(H-h)/2,fps=30,format=yuv420p[preZoom]`,
    `[preZoom]scale=1242:2208[big]`,
    `[big]crop=1080:1920:x='${xExpr}':y='${yExpr}'[out]`
  ].join(';');
  const scriptPath = `${outPath}.filters.txt`;
  await fsp.writeFile(scriptPath, filters);
  try {
    await execFileAsync(ffmpegPath, [
      '-loop', '1', '-t', segment.toFixed(2), '-i', stillPath,
      '-filter_complex_script', scriptPath, '-map', '[out]',
      '-c:v', 'libx264', '-preset', 'veryfast', '-crf', '20', '-r', '30', '-pix_fmt', 'yuv420p',
      '-y', outPath
    ], { maxBuffer: 1024 * 1024 * 50 });
  } finally {
    await fsp.unlink(scriptPath).catch(() => {});
  }
}

async function main() {
  const jobId = process.argv[2];
  if (!jobId) throw new Error('usage: node scripts/render-case-evidence.js <jobId>');

  const queue = JSON.parse(await fsp.readFile(QUEUE_PATH, 'utf8'));
  const job = queue.topics.find(j => j.id === jobId);
  if (!job) throw new Error(`no job "${jobId}" in the queue`);
  if (!job.caseNumber) throw new Error(`job "${jobId}" has no caseNumber`);

  const evidenceDir = path.join(REFERENCE_DIR, `case-${job.caseNumber}`);
  const stills = (await fsp.readdir(evidenceDir))
    .filter(f => /\.(jpe?g|png)$/i.test(f))
    .sort()
    .map(f => path.join(evidenceDir, f));
  if (!stills.length) throw new Error(`no evidence stills found in ${evidenceDir}`);
  console.log(`${stills.length} evidence stills:`, stills.map(f => path.basename(f)).join(', '));

  const audioPath = path.join(SHORTS_DIR, 'audio', `${jobId}_short.mp3`);
  const captionPath = path.join(SHORTS_DIR, 'captions', `${jobId}_short.ass`);
  const outputPath = path.join(SHORTS_DIR, 'video', `${jobId}_short.mp4`);
  await fsp.mkdir(path.dirname(outputPath), { recursive: true });

  const factory = new ShortsFactory({});
  const duration = await factory.probeDuration(audioPath);
  if (!duration) throw new Error('narration audio has no duration');
  const segment = duration / stills.length;
  const framesPerClip = Math.round(segment * 30);

  const tmpDir = await fsp.mkdtemp(path.join(os.tmpdir(), 'aftercache-render-'));
  try {
    console.log(`Pass 1/5: rendering ${stills.length} card clips sequentially...`);
    const clipPaths = [];
    for (let i = 0; i < stills.length; i++) {
      const clipPath = path.join(tmpDir, `clip${i}.mp4`);
      await renderCardClip(stills[i], i, segment, framesPerClip, clipPath);
      clipPaths.push(clipPath);
      console.log(`  clip ${i + 1}/${stills.length} done`);
    }

    console.log('Pass 2/5: concatenating clips (stream copy)...');
    const listPath = path.join(tmpDir, 'list.txt');
    await fsp.writeFile(listPath, clipPaths.map(p => `file '${p.replace(/\\/g, '/')}'`).join('\n'));
    const concatPath = path.join(tmpDir, 'concat.mp4');
    await execFileAsync(ffmpegPath, ['-f', 'concat', '-safe', '0', '-i', listPath, '-c', 'copy', '-y', concatPath]);

    console.log('Pass 3/5: vignette + typed CASE stamp + captions...');
    const stampAssPath = path.join(SHORTS_DIR, 'captions', `${jobId}_stamp.ass`);
    const clickTimes = await buildStampAss(job, duration, stampAssPath);
    const stampArg = stampAssPath.replace(/\\/g, '/').replace(/:/g, '\\:');
    const captionArg = captionPath.replace(/\\/g, '/').replace(/:/g, '\\:');
    const overlayFilters = [
      `[0:v]vignette=PI/5[mood]`,
      `[mood]subtitles='${stampArg}'[stamped]`,
      `[stamped]subtitles='${captionArg}':force_style='Alignment=2,MarginV=150'[out]`
    ].join(';');
    const overlayScriptPath = path.join(tmpDir, 'overlay.filters.txt');
    await fsp.writeFile(overlayScriptPath, overlayFilters);
    const silentVideoPath = path.join(tmpDir, 'silent.mp4');
    await execFileAsync(ffmpegPath, [
      '-i', concatPath, '-filter_complex_script', overlayScriptPath, '-map', '[out]',
      '-c:v', 'libx264', '-preset', 'veryfast', '-crf', '20', '-r', '30', '-pix_fmt', 'yuv420p',
      '-y', silentVideoPath
    ], { maxBuffer: 1024 * 1024 * 50 });

    console.log('Pass 4/5: synthesizing + mixing SFX bed with narration...');
    const sfxEvents = [
      ...Array.from({ length: stills.length - 1 }, (_, k) => ({ time: (k + 1) * segment, type: 'thump' })),
      ...clickTimes.map(time => ({ time, type: 'click' }))
    ];
    const sfxPath = path.join(tmpDir, 'sfx.wav');
    await buildSfxBed(sfxEvents, duration, sfxPath);
    const mixedAudioPath = path.join(tmpDir, 'mixed.wav');
    await execFileAsync(ffmpegPath, [
      '-i', audioPath, '-i', sfxPath,
      '-filter_complex', '[0:a][1:a]amix=inputs=2:duration=first:dropout_transition=0:weights=1 0.5:normalize=0[aout]',
      '-map', '[aout]', '-y', mixedAudioPath
    ], { maxBuffer: 1024 * 1024 * 50 });

    console.log('Pass 5/5: muxing final video + audio...');
    await execFileAsync(ffmpegPath, [
      '-i', silentVideoPath, '-i', mixedAudioPath,
      '-map', '0:v', '-map', '1:a', '-c:v', 'copy', '-c:a', 'aac', '-b:a', '128k',
      // moov atom at the front so web/chat video players can start streaming
      // immediately instead of needing the whole file first — without this
      // the last delivered videos opened to a black screen/error in-chat
      // despite being valid, playable files (confirmed fine in VLC-style players).
      '-movflags', '+faststart',
      '-shortest', '-y', outputPath
    ]);
  } finally {
    await fsp.rm(tmpDir, { recursive: true, force: true }).catch(() => {});
  }

  console.log('DONE:', outputPath);
}

main().catch(e => { console.error('FAILED:', e.message); process.exit(1); });
